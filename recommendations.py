def recommend_career(interests: str, preferred_tasks: str = ""):
    text = f"{interests} {preferred_tasks}".lower()
    scores = {}
    for key, career in CAREERS.items():
        score = sum(1 for word in career["keywords"] if word in text)
        scores[key] = score
    best = max(scores, key=scores.get)
    if scores[best] == 0:
        return "web"
    return best

def get_career_text(career_id):
    career = CAREERS.get(career_id)
    if not career:
        return "Профессия не найдена."
    return (
        f"💼 {career['title']}\n\n"
        f"🔎 Чем занимается:\n{career['description']}\n\n"
        f"✅ Почему может понравиться:\n{career['pros']}\n\n"
        f"⚠️ Что может быть сложным:\n{career['challenges']}"
    )
